import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { dayjs } from 'lib/dayjs'
import { projectLogic } from 'scenes/projectLogic'

import { transactionalEmailLogList } from 'products/messaging/frontend/generated/api'
import type {
    EmailDeliveryStatusEnumApi,
    TransactionalEmailLogEntryApi,
} from 'products/messaging/frontend/generated/api.schemas'

export const LOG_PAGE_SIZE = 50

// pinned: URL search params of the Log tab - renaming breaks shared links
const URL_PARAMS = ['search', 'status', 'email', 'days'] as const

export const LOG_DATE_RANGES = [
    { value: 1, label: 'Last 24 hours' },
    { value: 7, label: 'Last 7 days' },
    { value: 30, label: 'Last 30 days' },
] as const

export interface TransactionalEmailLogFilters {
    search: string
    status: EmailDeliveryStatusEnumApi | null
    // The workflow behind the transactional email, which the log filters on.
    workflowId: string | null
    days: number
}

export const DEFAULT_LOG_FILTERS: TransactionalEmailLogFilters = { search: '', status: null, workflowId: null, days: 7 }

interface LogPage {
    results: TransactionalEmailLogEntryApi[]
    hasMore: boolean
    // Every page of one listing reads the same window, so sends that arrive later don't shift the offsets.
    dateFrom: string
    dateTo: string
    filters: TransactionalEmailLogFilters
}

