import { MakeLogicType, afterMount, connect, kea, key, listeners, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { projectLogic } from 'scenes/projectLogic'
import { Scene } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { Breadcrumb } from '~/types'

import { transactionalEmailLogRetrieve } from 'products/messaging/frontend/generated/api'
import type { TransactionalEmailLogDetailApi } from 'products/messaging/frontend/generated/api.schemas'

export interface TransactionalEmailLogEntryLogicProps {
    messageId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface transactionalEmailLogEntryLogicValues {
    currentProjectId: number | null // projectLogic
    breadcrumbs: Breadcrumb[]
    email: TransactionalEmailLogDetailApi | null | undefined
    emailLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface transactionalEmailLogEntryLogicActions {
    loadEmail: () => any
    loadEmailFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadEmailSuccess: (
        email: TransactionalEmailLogDetailApi | null,
        payload?: any
    ) => {
        email: TransactionalEmailLogDetailApi | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface transactionalEmailLogEntryLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        breadcrumbs: (email: TransactionalEmailLogDetailApi | null | undefined, messageId: string) => Breadcrumb[]
    }
}

export type transactionalEmailLogEntryLogicType = MakeLogicType<
    transactionalEmailLogEntryLogicValues,
    transactionalEmailLogEntryLogicActions,
    TransactionalEmailLogEntryLogicProps,
    transactionalEmailLogEntryLogicMeta
>

export const transactionalEmailLogEntryLogic = kea<transactionalEmailLogEntryLogicType>([
    props({} as TransactionalEmailLogEntryLogicProps),
    key((props) => props.messageId),
    path((key) => [
        'products',
        'workflows',
        'frontend',
        'Transactional',
        'log',
        'transactionalEmailLogEntryLogic',
        key,
    ]),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    loaders(({ props, values }) => ({
        // undefined until the first load answers, null when the project has no send with this ID.
        email: [
            undefined as TransactionalEmailLogDetailApi | null | undefined,
            {
                loadEmail: async () => {
                    if (values.currentProjectId === null) {
                        return null
                    }
                    try {
                        return await transactionalEmailLogRetrieve(String(values.currentProjectId), props.messageId)
                    } catch (error: any) {
                        if (error?.status === 404) {
                            return null
                        }
                        throw error
                    }
                },
            },
        ],
    })),
    selectors({
        breadcrumbs: [
            (s, p) => [s.email, p.messageId],
            (email: TransactionalEmailLogDetailApi | null | undefined, messageId: string): Breadcrumb[] => [
                {
                    key: Scene.Transactional,
                    name: 'Transactional',
                    path: urls.transactional(),
                    iconType: 'transactional',
                },
                { key: 'log', name: 'Log', path: urls.transactionalLog(), iconType: 'transactional' },
                {
                    key: [Scene.TransactionalEmailLogEntry, messageId],
                    name: email?.recipient || 'Email',
                    iconType: 'transactional',
                },
            ],
        ],
    }),
    listeners(() => ({
        loadEmailSuccess: ({ email }) => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('transactional email log entry viewed', {
                found: !!email,
                status: email?.status,
                opened: email?.opened,
                clicked: email?.clicked,
            })
        },
    })),
    afterMount(({ actions }) => actions.loadEmail()),
])
